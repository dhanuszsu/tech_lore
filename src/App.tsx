import React, { useState, useMemo } from 'react';
import { Header } from './components/Header';
import { HeroEvidence } from './components/HeroEvidence';
import { TimelineRuler } from './components/TimelineRuler';
import { TopicIndex } from './components/TopicIndex';
import { TrendChart } from './components/TrendChart';
import { StatisticalGauges } from './components/StatisticalGauges';
import { EvidenceTimelineRail } from './components/EvidenceTimelineRail';
import { FiltersDrawer } from './components/FiltersDrawer';
import { ClusterStudio } from './components/ClusterStudio';
import { ProvenanceAudit } from './components/ProvenanceAudit';
import { FloatingToolRail } from './components/FloatingToolRail';

// Import verified JSON data artifacts generated by Python pipeline
import topicsDataRaw from './data/topics_metadata.json';
import timeseriesDataRaw from './data/timeseries_data.json';
import evidenceDataRaw from './data/evidence_catalog.json';
import kmeansDataRaw from './data/kmeans_results.json';
import pipelineSummaryRaw from './data/pipeline_summary.json';

import type { Topic, EvidenceEvent, CategoryBadge, KMeansExport, PipelineSummary } from './types';

export const App: React.FC = () => {
  // Navigation tabs
  const [activeTab, setActiveTab] = useState<'workbench' | 'clustering' | 'provenance'>('workbench');

  // Search & Filter state
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [selectedBadge, setSelectedBadge] = useState<CategoryBadge | 'all'>('all');
  const [activeYear, setActiveYear] = useState<number | null>(null);
  const [isFiltersOpen, setIsFiltersOpen] = useState<boolean>(false);

  // Selected topics for chart comparison (default to prominent archetypes)
  const [selectedTopicIds, setSelectedTopicIds] = useState<string[]>([
    'chatgpt',
    'large_language_models',
    'deep_learning',
    'metaverse'
  ]);
  const [primaryTopicId, setPrimaryTopicId] = useState<string>('chatgpt');

  // Selected event (e.g. clicked on chart milestone or evidence card)
  const [selectedEventId, setSelectedEventId] = useState<string | null>(null);

  // Cast imported data to typed interfaces
  const topics: Topic[] = topicsDataRaw.topics;
  const dates: string[] = timeseriesDataRaw.dates;
  const seriesData: Record<string, number[]> = timeseriesDataRaw.series;
  const events: EvidenceEvent[] = evidenceDataRaw.events as EvidenceEvent[];
  const badgeCounts: Record<string, number> = evidenceDataRaw.category_badge_counts;
  const kmeansData: KMeansExport = kmeansDataRaw as unknown as KMeansExport;
  const pipelineSummary: PipelineSummary = pipelineSummaryRaw as unknown as PipelineSummary;

  // Selected topic objects
  const selectedTopics = useMemo(() => {
    return topics.filter((t) => selectedTopicIds.includes(t.id));
  }, [topics, selectedTopicIds]);

  const primaryTopic = useMemo(() => {
    return topics.find((t) => t.id === primaryTopicId) || topics[0];
  }, [topics, primaryTopicId]);

  const primaryFeatures = useMemo(() => {
    return kmeansData.topic_features.find((f) => f.topic_id === primaryTopic.id);
  }, [kmeansData, primaryTopic]);

  // Year counts for ruler
  const { years, yearCounts } = useMemo(() => {
    const yrSet = new Set<number>();
    const counts: Record<number, number> = {};

    for (let y = 2026; y >= 2004; y--) {
      yrSet.add(y);
      counts[y] = 0;
    }

    for (const ev of events) {
      if (counts[ev.year] !== undefined) {
        counts[ev.year] += 1;
      }
    }

    return {
      years: Array.from(yrSet).sort((a, b) => b - a),
      yearCounts: counts
    };
  }, [events]);

  // Number of active filters for badge
  const activeFilterCount = (selectedBadge !== 'all' ? 1 : 0) + (activeYear !== null ? 1 : 0);

  // Toggle topic selection in chart overlays
  const handleToggleTopic = (topicId: string) => {
    if (selectedTopicIds.includes(topicId)) {
      if (selectedTopicIds.length > 1) {
        const next = selectedTopicIds.filter((id) => id !== topicId);
        setSelectedTopicIds(next);
        // If the removed topic was also focused, transfer focus to another active topic
        if (primaryTopicId === topicId) {
          setPrimaryTopicId(next[0]);
        }
      }
    } else {
      if (selectedTopicIds.length < 6) {
        setSelectedTopicIds([...selectedTopicIds, topicId]);
      }
    }
  };

  // Reset chart overlays down to just the single focused topic
  const handleClearOverlays = () => {
    setSelectedTopicIds([primaryTopicId]);
  };

  // Select event from chart or list
  const handleSelectEvent = (event: EvidenceEvent) => {
    setSelectedEventId(event.id);
    if (event.topics.length > 0) {
      const match = topics.find((t) => event.topics.includes(t.id));
      if (match && !selectedTopicIds.includes(match.id)) {
        if (selectedTopicIds.length < 6) {
          setSelectedTopicIds([...selectedTopicIds, match.id]);
        }
        setPrimaryTopicId(match.id);
      }
    }
  };

  // Jump from cluster studio to workbench with topic
  const handleTopicJumpFromCluster = (topicId: string) => {
    if (!selectedTopicIds.includes(topicId)) {
      setSelectedTopicIds([topicId, ...selectedTopicIds.slice(0, 3)]);
    }
    setPrimaryTopicId(topicId);
    setActiveTab('workbench');
  };

  // Export full JSON dataset
  const handleExportData = () => {
    const exportBundle = {
      metadata: {
        title: 'TECH LORE — Trend Archaeology Research Archive',
        exportDate: new Date().toISOString(),
        dataset: '24 AI Topics Historical Corpus (2004–2026)',
        totalObservations: dates.length * topics.length
      },
      topics,
      dates,
      timeseries: seriesData,
      evidenceEvents: events,
      clustering: kmeansData,
      verificationAudit: pipelineSummary
    };

    const blob = new Blob([JSON.stringify(exportBundle, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `tech_lore_trend_archaeology_${new Date().toISOString().slice(0, 10)}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleResetView = () => {
    setSelectedBadge('all');
    setActiveYear(null);
    setSearchQuery('');
    setSelectedEventId(null);
  };

  return (
    <div className="app-container">
      {/* 1. Header Bar */}
      <Header
        activeTab={activeTab}
        setActiveTab={setActiveTab}
        searchQuery={searchQuery}
        setSearchQuery={setSearchQuery}
        onExport={handleExportData}
      />

      {/* 2. Hero Section (TECH LORE / Before it was everywhere. / Archive Metadata Line) */}
      <HeroEvidence totalEvents={events.length} />

      {/* 3. Horizontal Historical Scrubber (Archive Ruler with Density Ticks & Baseline) */}
      <TimelineRuler
        years={years}
        activeYear={activeYear}
        onSelectYear={setActiveYear}
        yearCounts={yearCounts}
      />

      {/* 4. Main Body Content Based on Active Tab */}
      {activeTab === 'workbench' && (
        <>
          {/* 4a. Curated Topic Archival Index (01–24 Catalog with Focused, Active, Inactive states) */}
          <TopicIndex
            topics={topics}
            selectedTopicIds={selectedTopicIds}
            primaryTopicId={primaryTopicId}
            onToggleTopic={handleToggleTopic}
            onSetFocusTopic={setPrimaryTopicId}
            onClearOverlays={handleClearOverlays}
          />

          {/* 4b. Investigation Split Layout (Quantitative Trend Curve | Historical Catalyst Stream) */}
          <main className="workbench-split-layout">
            {/* Left Pane: Interactive Trend Curve + Statistical Gauges */}
            <div className="workbench-left-pane">
              <TrendChart
                dates={dates}
                seriesData={seriesData}
                selectedTopics={selectedTopics}
                events={events}
                activeYear={activeYear}
                onSelectEvent={handleSelectEvent}
                selectedEventId={selectedEventId}
                onOpenFilters={() => setIsFiltersOpen(true)}
                activeFilterCount={activeFilterCount}
              />

              {/* Research Measurement Bar (Border-free / hairline divided) */}
              <StatisticalGauges
                primaryTopic={primaryTopic}
                features={primaryFeatures}
              />
            </div>

            {/* Right Pane: Historical Catalyst Evidence Rail */}
            <EvidenceTimelineRail
              events={events}
              selectedBadge={selectedBadge}
              activeYear={activeYear}
              selectedEventId={selectedEventId}
              onSelectEvent={handleSelectEvent}
              searchQuery={searchQuery}
            />
          </main>
        </>
      )}

      {/* 5. ML Cluster Studio Tab */}
      {activeTab === 'clustering' && (
        <ClusterStudio
          topics={topics}
          kmeansData={kmeansData}
          onSelectTopic={handleTopicJumpFromCluster}
        />
      )}

      {/* 6. Provenance & Audit Tab */}
      {activeTab === 'provenance' && (
        <ProvenanceAudit
          summary={pipelineSummary}
          onExport={handleExportData}
        />
      )}

      {/* 7. Dedicated Filters Slide-Out Drawer */}
      <FiltersDrawer
        isOpen={isFiltersOpen}
        onClose={() => setIsFiltersOpen(false)}
        selectedBadge={selectedBadge}
        onSelectBadge={setSelectedBadge}
        badgeCounts={badgeCounts}
        activeYear={activeYear}
        onSelectYear={setActiveYear}
        totalEvents={events.length}
      />

      {/* 8. Floating Right-Hand Docked Tool Rail */}
      <FloatingToolRail
        activeTab={activeTab}
        setActiveTab={setActiveTab}
        onResetView={handleResetView}
      />
    </div>
  );
};

export default App;
